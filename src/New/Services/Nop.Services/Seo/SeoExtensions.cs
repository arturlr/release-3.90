    /// <summary>
    /// Get search engine friendly name (slug) for an entity via URL record lookup.
    /// </summary>
    public static async Task<string> GetSeNameAsync<T>(this T entity, int languageId,
        IUrlRecordService urlRecordService, ILanguageService? languageService = null,
        bool returnDefaultValue = true, bool ensureTwoPublishedLanguages = true)
        where T : BaseEntity, ISlugSupported
    {
        ArgumentNullException.ThrowIfNull(entity);
        var entityName = typeof(T).Name;
        var result = string.Empty;

        if (languageId > 0)
        {
            var loadLocalized = true;
            if (ensureTwoPublishedLanguages && languageService != null)
            {
                var languages = await languageService.GetAllLanguagesAsync();
                loadLocalized = languages.Count >= 2;
            }
            if (loadLocalized)
                result = await urlRecordService.GetActiveSlugAsync(entity.Id, entityName, languageId);
        }

        if (string.IsNullOrEmpty(result) && returnDefaultValue)
            result = await urlRecordService.GetActiveSlugAsync(entity.Id, entityName, 0);

        return result;
    }

    /// <summary>
    /// Validate and ensure uniqueness of a search engine name.
    /// </summary>
    public static async Task<string> ValidateSeNameAsync<T>(this T entity, string? seName, string? name,
        bool ensureNotEmpty, IUrlRecordService urlRecordService, SeoSettings seoSettings)
        where T : BaseEntity, ISlugSupported
    {
        ArgumentNullException.ThrowIfNull(entity);
        return await ValidateSeNameAsync(entity.Id, typeof(T).Name, seName, name,
            ensureNotEmpty, urlRecordService, seoSettings);
    }

    /// <summary>
    /// Validate and ensure uniqueness of a search engine name by entity ID/name.
    /// </summary>
    public static async Task<string> ValidateSeNameAsync(int entityId, string entityName, string? seName,
        string? name, bool ensureNotEmpty, IUrlRecordService urlRecordService, SeoSettings seoSettings)
    {
        if (string.IsNullOrWhiteSpace(seName) && !string.IsNullOrWhiteSpace(name))
            seName = name;

        seName = GetSeName(seName, seoSettings.ConvertNonWesternChars, seoSettings.AllowUnicodeCharsInUrls);
        seName = CommonHelper.EnsureMaximumLength(seName, 200);

        if (string.IsNullOrWhiteSpace(seName))
        {
            if (ensureNotEmpty)
                seName = entityId.ToString();
            else
                return seName ?? string.Empty;
        }

        var i = 2;
        var tempSeName = seName;
        while (true)
        {
            var urlRecord = await urlRecordService.GetBySlugAsync(tempSeName);
            var reserved1 = urlRecord != null &&
                !(urlRecord.EntityId == entityId && string.Equals(urlRecord.EntityName, entityName, StringComparison.InvariantCultureIgnoreCase));
            var reserved2 = seoSettings.ReservedUrlRecordSlugs.Contains(tempSeName, StringComparer.InvariantCultureIgnoreCase);
            if (!reserved1 && !reserved2)
                break;
            tempSeName = $"{seName}-{i}";
            i++;
        }

        return tempSeName;
    }

    /// <summary>
    /// Generate a clean, URL-safe slug from a name string.
    /// </summary>
    public static string GetSeName(string? name, bool convertNonWesternChars, bool allowUnicodeCharsInUrls)
    {
        if (string.IsNullOrEmpty(name))
            return string.Empty;

        const string okChars = "abcdefghijklmnopqrstuvwxyz1234567890 _-";
        name = name.Trim().ToLowerInvariant();

        var sb = new StringBuilder(name.Length);
        foreach (var c in name)
        {
            var replacement = c.ToString();
            if (convertNonWesternChars && CharacterTable.TryGetValue(c, out var mapped))
                replacement = mapped;

            if (allowUnicodeCharsInUrls)
            {
                if (char.IsLetterOrDigit(c) || okChars.Contains(replacement, StringComparison.Ordinal))
                    sb.Append(replacement);
            }
            else if (okChars.Contains(replacement, StringComparison.Ordinal))
            {
                sb.Append(replacement);
            }
        }

        var result = sb.ToString().Replace(' ', '-');
        // Collapse consecutive hyphens and underscores
        int len;
        do
        {
            len = result.Length;
            result = result.Replace("--", "-").Replace("__", "_");
        } while (result.Length != len);

        return result;
    }
